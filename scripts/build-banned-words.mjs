#!/usr/bin/env node
/**
 * Builds backend/config/banned_words.txt and mobile/src/moderation/bannedWords.generated.ts
 * from vendored LDNOOBW lists (third_party/ldnoobw/) + scripts/banned-words-exclusions.json
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "..");

const LDNOOBW_DIR = path.join(repoRoot, "third_party", "ldnoobw");
const EXCLUSIONS_PATH = path.join(repoRoot, "scripts", "banned-words-exclusions.json");
const BACKEND_OUT = path.join(repoRoot, "backend", "config", "banned_words.txt");
const MOBILE_OUT = path.join(
  repoRoot,
  "mobile",
  "src",
  "moderation",
  "bannedWords.generated.ts",
);

function readLines(filePath) {
  return fs
    .readFileSync(filePath, "utf8")
    .split(/\r?\n/)
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith("#"));
}

function loadExclusions() {
  const raw = JSON.parse(fs.readFileSync(EXCLUSIONS_PATH, "utf8"));
  return {
    en: new Set(raw.en ?? []),
    ko: new Set(raw.ko ?? []),
  };
}

function mergeLists() {
  const exclusions = loadExclusions();
  const en = readLines(path.join(LDNOOBW_DIR, "en")).filter((w) => !exclusions.en.has(w));
  const ko = readLines(path.join(LDNOOBW_DIR, "ko")).filter((w) => !exclusions.ko.has(w));
  const merged = [...new Set([...en, ...ko])].sort((a, b) => a.localeCompare(b, "ko"));
  return { merged, enCount: en.length, koCount: ko.length };
}

function writeBackendTxt(terms) {
  fs.mkdirSync(path.dirname(BACKEND_OUT), { recursive: true });
  const header = [
    "# Factfulness banned-word list — AUTO-GENERATED by scripts/build-banned-words.mjs",
    "# Sources: third_party/ldnoobw/en + ko (LDNOOBW, CC BY 4.0) — see third_party/ldnoobw/ATTRIBUTION.md",
    "# Do not edit by hand; run: node scripts/build-banned-words.mjs",
    "",
  ].join("\n");
  fs.writeFileSync(BACKEND_OUT, header + terms.join("\n") + "\n", "utf8");
}

function writeMobileTs(terms) {
  const body = terms.map((t) => JSON.stringify(t)).join(",\n  ");
  const content = `/** AUTO-GENERATED — do not edit. Run: node scripts/build-banned-words.mjs */\nexport const BANNED_WORDS: readonly string[] = [\n  ${body},\n] as const;\n`;
  fs.writeFileSync(MOBILE_OUT, content, "utf8");
}

const { merged, enCount, koCount } = mergeLists();
writeBackendTxt(merged);
writeMobileTs(merged);
console.log(
  `Wrote ${merged.length} terms (${enCount} en + ${koCount} ko after exclusions) →`,
  path.relative(repoRoot, BACKEND_OUT),
  "and",
  path.relative(repoRoot, MOBILE_OUT),
);
